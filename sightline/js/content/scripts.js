export const ALL_SCRIPTS = SCRIPTS;

// The scripts for a sport, with each line chosen for the athlete's position.
export function scriptsFor(sport = 'general', position = '') {
  const list = SCRIPTS[sport] ?? SCRIPTS.general;
  return list.map((s) => ({
    ...s,
    lines: s.lines.map(([text, sec, tag]) => [typeof text === 'string' ? text : (text[position] ?? text.default), sec, tag]),
  }));
}

export const scriptSeconds = (s) => s.lines.reduce((a, [, sec]) => a + sec, 0);
