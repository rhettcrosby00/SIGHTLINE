export function icon(name, { size = 20, label = '' } = {}) {
  const body = PATHS[name] ?? '';
  const a11y = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true"';
  return `<svg class="icon icon-${name}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${body}</svg>`;
}

// Replace every <i data-icon="name"> in a container with its SVG.
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon, { size: Number(el.dataset.size) || 20, label: el.getAttribute('aria-label') || '' });
  });
}
